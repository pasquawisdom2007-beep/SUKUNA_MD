function cleanText(text) {
    return String(text || '').replace(/[\r\n]+/g, ' ').replace(/[<>]/g, '').trim().slice(0, 90);
}

function normalizeStyle(style) {
    return STYLE_PRESETS[style] || STYLE_PRESETS.gradient;
}

function makeKeylessTextImageUrl(text, style = 'gradient') {
    const clean = cleanText(text);
    if (!clean) throw new Error('Text is required');
    const preset = normalizeStyle(style);
    const lines = [preset.prefix, clean, preset.suffix].join('\n');
    const params = new URLSearchParams({ text: lines, font: 'bold' });
    return `https://placehold.co/1200x630/${preset.background}/${preset.foreground}/png?${params.toString()}`;
}

function withTimeout(promise, timeoutMs) {
    let timer;
    const timeout = new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error(`EPhoto360 timed out after ${timeoutMs}ms`)), timeoutMs);
    });
    return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

async function generateEphotoImage(effectUrl, text, timeoutMs = 45000) {
    if (!effectUrl || !/photo360\.com/i.test(effectUrl)) {
        throw new Error('Invalid EPhoto360 effect URL');
    }
    const generator = new Photo360(effectUrl);
    generator.setName(text);
    const result = await withTimeout(generator.execute(), timeoutMs);
    if (!result || result.status === false || !result.imageUrl) {
        throw new Error('EPhoto360 returned no generated image');
    }
    return result.imageUrl;
}

async function fetchEphoto(effectUrl, text, style = 'gradient') {
    const clean = cleanText(text);
    if (!clean) throw new Error('Text is required');
    try {
        return await generateEphotoImage(effectUrl, clean);
    } catch (error) {
        console.error(`[textmaker] EPhoto360 failed for ${effectUrl}:`, error.message);
        if (String(process.env.TEXTMAKER_DISABLE_FALLBACK).toLowerCase() === 'true') throw error;
        return makeKeylessTextImageUrl(clean, style);
    }
}

function makeTextmakerCommand({ name, ephotoUrl, label, emoji = '✨', aliases = [], style }) {
    const selectedStyle = style || name.replace(/text$/i, '').toLowerCase();
    return {
        name,
        aliases,
        description: `${label} text effect powered by EPhoto360`,
        category: 'textmaker',
        async execute({ sock, msg, from, args }) {
            if (!args.length) {
                return sock.sendMessage(from, messageTemplates.error(
                    `${emoji} *${label}*\n\nUsage: .${name} <text>\nExample: .${name} SUKUNA`
                ), { quoted: msg });
            }
            const text = cleanText(args.join(' '));
            try {
                await sock.sendMessage(from, { react: { text: '⏳', key: msg.key } });
                const imageUrl = await fetchEphoto(ephotoUrl, text, selectedStyle);
                const isFallback = imageUrl.includes('placehold.co');
                const providerLabel = isFallback ? 'FALLBACK' : 'EPHOTO360';
                const caption = `${emoji} *${label}*\n╰─ ${text}\n\n> SUKUNA MD • ${providerLabel}`;
                await sock.sendMessage(from, messageTemplates.success(imageUrl, caption), { quoted: msg });
                await sock.sendMessage(from, { react: { text: '✅', key: msg.key } });
            } catch (err) {
                console.error(`[${name}] error:`, err.message);
                try { await sock.sendMessage(from, { react: { text: '❌', key: msg.key } }); } catch {}
                await sock.sendMessage(from, messageTemplates.error(`❌ ${label} failed: ${err.message}`), { quoted: msg });
            }
        },
    };
}

