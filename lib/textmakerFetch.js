/**
 * Text-maker image helper backed by the real EPhoto360 generator.
 *
 * EPhoto360 is not an official API, so the wrapper is isolated here. If the
 * public site is unavailable or changes its form, a stable fallback URL keeps
 * the command from crashing; successful requests always return the real
 * generated EPhoto360 image URL.
 */
